#!/bin/bash
# Writes a Netlify _redirects file that turns every Hugo alias into a real
# HTTP 301.
#
# Netlify reads it on deploy previews and branch deploys. Production is served
# by GitHub Pages, which ignores _redirects; there the alias pages themselves
# (layouts/alias.html) carry a visible link to the new URL.
#
# Hugo publishes an alias as a stub page holding only
# <meta http-equiv="refresh">. Browsers follow it; fetch tools, crawlers and
# coding agents do not, and get an empty page instead (see #2968).
#
# The rules are read from the stub pages Hugo actually wrote, not from front
# matter, so they match the published site exactly: an alias that collides
# with a real page (Hugo publishes the page, not the stub) gets no rule, and
# where two pages claim the same alias the rule points where Hugo's stub does.
# Pagination aliases (/blog/page/1/) are covered the same way.
#
# The stubs stay published as a fallback, so each rule is forced ("301!"):
# Netlify otherwise skips a rule when a file exists at its "from" path.
#
# Usage: scripts/generate-redirects.sh [public dir]   (default: website_and_docs/public)
set -euo pipefail

PUBLIC_DIR="${1:-website_and_docs/public}"
PUBLIC_DIR="${PUBLIC_DIR%/}"
OUT="${PUBLIC_DIR}/_redirects"

if [[ ! -d "${PUBLIC_DIR}" ]]; then
  echo "generate-redirects: ${PUBLIC_DIR} does not exist, build the site first" >&2
  exit 1
fi

tmp=$(mktemp)
trap 'rm -f "${tmp}"' EXIT

# Alias stubs are about 1 KB; real pages are far larger, so the size
# filter keeps grep off the bulk of the site.
find "${PUBLIC_DIR}" -type f -name '*.html' -size -8k -print0 |
  xargs -0 grep -l -E 'http-equiv="?refresh' 2>/dev/null |
  while IFS= read -r stub; do
    # Matches both minified (content="0; url=...") and unminified output.
    target=$(sed -n -E 's/.*http-equiv="?refresh"? content="0; ?url=([^"]+)".*/\1/p' "${stub}" | head -n 1)
    [[ -z "${target}" ]] && continue
    # Strip scheme and host so the rule works on every deploy (each preview
    # and branch deploy builds with its own baseURL).
    target=$(printf '%s' "${target}" | sed -E 's#^[a-zA-Z][a-zA-Z0-9+.-]*://[^/]+##')
    [[ -z "${target}" ]] && target="/"
    from="${stub#"${PUBLIC_DIR}"}"
    from="${from%index.html}"
    [[ "${from}" == "${target}" ]] && continue
    printf '%s %s 301!\n' "${from}" "${target}"
  done | LC_ALL=C sort -u > "${tmp}"

{
  echo "# Generated by scripts/generate-redirects.sh from Hugo alias pages. Do not edit."
  cat "${tmp}"
} > "${OUT}"

echo "generate-redirects: wrote $(wc -l < "${tmp}" | tr -d ' ') rules to ${OUT}"
